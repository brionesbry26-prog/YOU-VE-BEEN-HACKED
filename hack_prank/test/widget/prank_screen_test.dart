import '../helpers/fakes.dart';

const _fifteen = PrankSettings(countdownSeconds: 15);
final _timeline = PrankTimeline(ransomDuration: const Duration(seconds: 15));

/// Fake time at which [stage] begins (the run starts on the first frame).
Duration startOf(PrankStage stage) => _timeline.startOf(stage);

/// Pumps until [time] after launch, given [now] has already elapsed.
Future<void> pumpUntil(WidgetTester tester, Duration now, Duration time) =>
    pumpFor(tester, time - now);

/// Sends a lifecycle change the way the engine does; intermediate states
/// (inactive, hidden) are generated by the framework.
Future<void> setLifecycle(WidgetTester tester, AppLifecycleState state) async {
  final message = const StringCodec().encodeMessage(state.toString());
  await tester.binding.defaultBinaryMessenger.handlePlatformMessage(
    'flutter/lifecycle',
    message,
    (_) {},
  );
}

/// Waits for the route transition to the awareness screen.
Future<void> settleReveal(WidgetTester tester) => pumpFor(tester, const Duration(milliseconds: 800));

void expectLesson() {
  expect(find.byType(RevealScreen), findsOneWidget);
  expect(find.text(PrankConstants.lessonHeadline), findsOneWidget);
  expect(find.text(PrankConstants.lessonSubline), findsOneWidget);
  expect(find.byType(PrankScreen), findsNothing);
}

void main() {
  testWidgets('opening the app starts the simulation automatically', (tester) async {
    final s = TestServices(_fifteen);
    await launchApp(tester, s);

    // No home screen or manual controls.
    for (final text in ['START THE PRANK', 'CUSTOMIZE EXPERIENCE', 'Start', 'Reveal', 'WAIT... WHAT?!']) {
      expect(find.text(text), findsNothing, reason: text);
    }

    // First: the innocent title card.
    await pumpFor(tester, const Duration(seconds: 1));
    expect(find.byKey(PrankScreen.introKey), findsOneWidget);
    expect(find.text('I Love You'), findsOneWidget);
    expect(s.audio.audible, [SoundEffect.startup]);

    // Then, without any input: the terminal.
    await pumpUntil(tester, const Duration(seconds: 1), startOf(PrankStage.initializing) + const Duration(milliseconds: 800));
    expect(find.byKey(PrankScreen.introKey), findsNothing);
    expect(find.text('I Love You'), findsNothing);
    expect(find.textContaining('STAGE 1/5'), findsOneWidget);
    expect(find.textContaining('INITIALIZING CONNECTION'), findsOneWidget);
    expect(find.textContaining('SCANNING SIMULATED ENVIRONMENT'), findsNothing,
        reason: 'still typing');
  });

  testWidgets('the title card plays again on every launch', (tester) async {
    for (var launch = 0; launch < 2; launch++) {
      final s = TestServices(_fifteen);
      await launchApp(tester, s);
      await pumpFor(tester, const Duration(milliseconds: 800));
      expect(find.text('I Love You'), findsOneWidget, reason: 'launch $launch');
      await pumpFor(tester, startOf(PrankStage.initializing) + const Duration(seconds: 1));
      expect(find.textContaining('STAGE 1/5'), findsOneWidget);
      // "Close" the app.
      await tester.pumpWidget(const SizedBox());
      await tester.pump();
    }
  });

  testWidgets('every stage shows its content and the countdown ends in the lesson', (tester) async {
    final s = TestServices(_fifteen);
    await launchApp(tester, s);
    var now = Duration.zero;
    Future<void> goTo(PrankStage stage) async {
      final target = startOf(stage) + const Duration(milliseconds: 3500);
      await pumpUntil(tester, now, target);
      now = target;
    }

    await goTo(PrankStage.activity);
    expect(find.textContaining('STAGE 2/5'), findsOneWidget);
    expect(find.textContaining('REMOTE CONNECTION DETECTED'), findsOneWidget);
    expect(find.textContaining('DATA TRANSFER: 47%'), findsOneWidget);
    expect(find.textContaining('REMOTE NODE: '), findsOneWidget);

    await goTo(PrankStage.warning);
    expect(find.textContaining('STAGE 3/5'), findsOneWidget);
    expect(find.text(PrankConstants.alertTitle), findsWidgets);
    expect(find.text(PrankConstants.alertSubtitle), findsOneWidget);

    await goTo(PrankStage.extracting);
    expect(find.textContaining('STAGE 4/5'), findsOneWidget);
    for (final f in PrankConstants.simulatedFiles) {
      expect(find.text(f.name), findsOneWidget, reason: f.name);
    }

    await goTo(PrankStage.ransom);
    expect(find.byType(RansomScreen), findsOneWidget);
    expect(find.text(PrankConstants.compromisedStatus), findsWidgets);
    expect(find.text(PrankConstants.simulationInProgress), findsOneWidget);
    expect(find.text('TIME REMAINING:'), findsOneWidget);
    expect(find.text('00:12'), findsOneWidget, reason: '3.5 s into a 15 s countdown');
    expect(find.textContaining('₱'), findsNothing, reason: 'no payment demand');
    expect(s.audio.loop, SoundEffect.countdown);

    // The countdown always ends in the lesson.
    await pumpUntil(tester, now, _timeline.total);
    await settleReveal(tester);
    expectLesson();

    // Everything stopped.
    expect(s.audio.loop, isNull);
    expect(s.shake.isListening, isFalse);
    expect(s.wakelock.enabled, isFalse);
    expect(s.audio.audible.last, SoundEffect.reveal);
    expect(s.haptics.pulses.last, HapticCue.reveal);
    final sounds = s.audio.audible.length;
    await pumpFor(tester, const Duration(seconds: 20));
    expect(s.audio.audible.length, sounds, reason: 'no sound after the reveal');
  });

  testWidgets('shaking is ignored during the title card', (tester) async {
    final s = TestServices(_fifteen);
    await launchApp(tester, s);
    await pumpFor(tester, const Duration(seconds: 1));
    expect(s.shake.shake(), isFalse);
    expect(find.byType(RevealScreen), findsNothing);
  });

  for (final stage in PrankStage.numbered) {
    testWidgets('shaking the phone reveals the lesson during ${stage.name}', (tester) async {
      final s = TestServices(_fifteen);
      await launchApp(tester, s);
      await pumpFor(tester, startOf(stage) + const Duration(milliseconds: 500));
      expect(s.shake.isListening, isTrue);

      expect(s.shake.shake(), isTrue);
      expect(s.shake.isListening, isFalse, reason: 'sensor released on reveal');
      expect(s.audio.loop, isNull, reason: 'audio stopped on reveal');
      expect(s.haptics.cancels, greaterThanOrEqualTo(1));
      await settleReveal(tester);
      expectLesson();
    });
  }

  testWidgets('no visible reveal button exists during the simulation', (tester) async {
    final s = TestServices(_fifteen);
    await launchApp(tester, s);
    await pumpFor(tester, startOf(PrankStage.ransom) + const Duration(seconds: 1));
    expect(find.text('Reveal'), findsNothing);
    expect(find.text('WAIT... WHAT?!'), findsNothing);
    expect(find.byType(TextButton), findsNothing);
    s.shake.shake();
    await settleReveal(tester);
  });

  testWidgets('✕ asks for confirmation; CONTINUE PRANK resumes', (tester) async {
    final s = TestServices(_fifteen);
    await launchApp(tester, s);
    await pumpFor(tester, startOf(PrankStage.initializing) + const Duration(seconds: 1));

    await tester.tap(find.byKey(PrankScreen.exitKey));
    await pumpFor(tester, const Duration(milliseconds: 300));
    expect(find.byType(ExitConfirmationDialog), findsOneWidget);
    expect(find.text('End the simulation?'), findsOneWidget);
    expect(s.shake.isListening, isFalse, reason: 'paused while the dialog is open');

    await pumpFor(tester, const Duration(seconds: 30));
    expect(find.textContaining('STAGE 1/5'), findsOneWidget, reason: 'frozen');

    await tester.tap(find.text('CONTINUE PRANK'));
    await pumpFor(tester, const Duration(milliseconds: 300));
    expect(find.byType(ExitConfirmationDialog), findsNothing);
    expect(s.shake.isListening, isTrue);

    await pumpFor(tester, const Duration(seconds: 4));
    expect(find.textContaining('STAGE 2/5'), findsOneWidget);
    s.shake.shake();
    await settleReveal(tester);
  });

  testWidgets('EXIT SAFELY stops everything and explains what happened', (tester) async {
    final s = TestServices(_fifteen);
    await launchApp(tester, s);
    await pumpFor(tester, startOf(PrankStage.extracting) + const Duration(milliseconds: 500));
    expect(s.audio.loop, SoundEffect.transfer);
    expect(s.wakelock.enabled, isTrue);

    await tester.tap(find.byKey(PrankScreen.exitKey));
    await pumpFor(tester, const Duration(milliseconds: 300));
    await tester.tap(find.text('EXIT SAFELY'));
    await settleReveal(tester);

    expectLesson();
    expect(s.audio.loop, isNull);
    expect(s.wakelock.enabled, isFalse);
    expect(s.shake.isListening, isFalse);
  });

  testWidgets('the system back gesture also offers a safe exit', (tester) async {
    final s = TestServices(_fifteen);
    await launchApp(tester, s);
    await pumpFor(tester, startOf(PrankStage.activity));

    // What the Android back button / gesture does.
    final navigator = tester.state<NavigatorState>(find.byType(Navigator));
    await navigator.maybePop();
    await pumpFor(tester, const Duration(milliseconds: 300));
    expect(find.byType(ExitConfirmationDialog), findsOneWidget);

    await tester.tap(find.text('EXIT SAFELY'));
    await settleReveal(tester);
    expectLesson();
  });

  testWidgets('without exit confirmation, ✕ ends the simulation immediately', (tester) async {
    final s = TestServices(_fifteen.copyWith(exitConfirmation: false));
    await launchApp(tester, s);
    await pumpFor(tester, startOf(PrankStage.warning));

    await tester.tap(find.byKey(PrankScreen.exitKey));
    await settleReveal(tester);
    expect(find.byType(ExitConfirmationDialog), findsNothing);
    expectLesson();
  });

  testWidgets('triple-tapping the stage title ends it (accessibility fallback)', (tester) async {
    final s = TestServices(_fifteen);
    await launchApp(tester, s);
    await pumpFor(tester, startOf(PrankStage.activity));

    for (var i = 0; i < 3; i++) {
      await tester.tap(find.byKey(PrankScreen.titleKey));
      await tester.pump(const Duration(milliseconds: 50));
    }
    await settleReveal(tester);
    expectLesson();
  });

  testWidgets('backgrounding pauses everything; resuming continues without restarting', (tester) async {
    final s = TestServices(_fifteen);
    await launchApp(tester, s);
    final at = startOf(PrankStage.ransom) + const Duration(seconds: 2);
    await pumpFor(tester, at);
    expect(find.text('00:13'), findsOneWidget);

    await setLifecycle(tester, AppLifecycleState.paused);
    await tester.pump();
    expect(s.audio.loop, isNull);
    expect(s.wakelock.enabled, isFalse);
    expect(s.shake.isListening, isFalse);

    await pumpFor(tester, const Duration(minutes: 1));
    expect(find.byType(RevealScreen), findsNothing, reason: 'time froze');

    await setLifecycle(tester, AppLifecycleState.resumed);
    await tester.pump();
    expect(s.wakelock.enabled, isTrue);
    expect(s.shake.isListening, isTrue);
    expect(s.audio.loop, SoundEffect.countdown);
    expect(find.text('00:13'), findsOneWidget, reason: 'countdown did not restart');

    await pumpFor(tester, const Duration(seconds: 13));
    await settleReveal(tester);
    expectLesson();
  });

  testWidgets('works end to end with every optional effect disabled', (tester) async {
    final s = TestServices(allEffectsOff);
    await launchApp(tester, s);
    await pumpFor(tester, startOf(PrankStage.initializing) + const Duration(milliseconds: 800));

    // Typewriter off: the full text is shown at once.
    expect(find.textContaining('SCANNING SIMULATED ENVIRONMENT'), findsOneWidget);

    await pumpFor(tester, _timeline.total);
    await settleReveal(tester);
    expectLesson();
    expect(s.audio.audible, isEmpty);
    expect(s.haptics.pulses, isEmpty);
  });

  testWidgets('REPLAY starts again from the title card', (tester) async {
    final s = TestServices(_fifteen);
    await launchApp(tester, s);
    await pumpFor(tester, startOf(PrankStage.warning));
    s.shake.shake();
    await settleReveal(tester);

    await tester.ensureVisible(find.byKey(RevealScreen.replayKey));
    await tester.tap(find.byKey(RevealScreen.replayKey));
    await tester.pump();
    await pumpFor(tester, const Duration(milliseconds: 900));

    expect(find.byType(PrankScreen), findsOneWidget);
    expect(find.text('I Love You'), findsOneWidget);
    expect(find.byType(RevealScreen), findsNothing);
  });
}
