const _fifteen = PrankSettings(durationSeconds: 15);

/// Opens the prank from the home screen.
Future<void> startPrank(WidgetTester tester, TestServices s) async {
  await pumpApp(tester, s);
  await tester.tap(find.byKey(HomeScreen.startKey));
  // Route transition plus the post-frame start.
  await tester.pump();
  await tester.pump(const Duration(milliseconds: 450));
}

/// Sends a lifecycle change the way the engine does; intermediate states
/// (inactive, hidden) are generated by the framework.
Future<void> setLifecycle(WidgetTester tester, AppLifecycleState state) async {
  final message = const StringCodec().encodeMessage(state.toString());
  await tester.binding.defaultBinaryMessenger.handlePlatformMessage(
    'flutter/lifecycle',
    message,
    (_) {},
  );
}

Duration stageStart(PrankStage stage, int seconds) =>
    PrankTimeline.forTotal(Duration(seconds: seconds)).startOf(stage);

void main() {
  testWidgets('runs start to finish and reveals automatically', (tester) async {
    final s = TestServices(_fifteen);
    await startPrank(tester, s);

    expect(find.textContaining('STAGE 1/6'), findsOneWidget);
    expect(find.textContaining('ANALYZING TARGET SYSTEM'), findsNothing,
        reason: 'the typewriter has not reached the last line yet');

    await pumpFor(tester, stageStart(PrankStage.tracing, 15));
    expect(find.textContaining('STAGE 2/6'), findsOneWidget);

    await pumpFor(tester, stageStart(PrankStage.ransom, 15) - stageStart(PrankStage.tracing, 15));
    expect(find.byType(RansomScreen), findsOneWidget);
    expect(find.text('YOUR DEVICE HAS BEEN HACKED!'), findsWidgets);
    expect(find.text('PAY ₱500 TO RESTORE ACCESS'), findsOneWidget);
    expect(find.text('WAIT... WHAT?!'), findsOneWidget);

    // 15s total: the ransom countdown is 5s.
    await pumpFor(tester, const Duration(seconds: 5));
    await pumpFor(tester, const Duration(milliseconds: 600));
    expect(find.byType(RevealScreen), findsOneWidget);
    expect(find.text('GOTCHA! 😂'), findsOneWidget);
    expect(find.byType(PrankScreen), findsNothing);

    // Every stage played its sounds; then the prank audio was stopped.
    expect(s.audio.audible, containsAll([SoundEffect.typing, SoundEffect.alarm, SoundEffect.voice, SoundEffect.siren]));
    expect(s.audio.audible.last, SoundEffect.celebrate);
    expect(s.audio.loop, isNull);
    expect(s.haptics.pulses.last, HapticCue.reveal);
    expect(s.wakelock.enabled, isFalse);
    await pumpFor(tester, const Duration(seconds: 4));
  });

  for (final stage in [...PrankStage.sequence, PrankStage.ransom]) {
    testWidgets('the Reveal shortcut works during ${stage.name}', (tester) async {
      final s = TestServices(_fifteen);
      await startPrank(tester, s);
      await pumpFor(tester, stageStart(stage, 15) + const Duration(milliseconds: 100));

      await tester.tap(find.byKey(PrankScreen.revealKey));
      await pumpFor(tester, const Duration(milliseconds: 600));
      expect(find.byType(RevealScreen), findsOneWidget);
      expect(s.audio.prankStops, greaterThanOrEqualTo(1));
      await pumpFor(tester, const Duration(seconds: 4));
    });
  }

  testWidgets('WAIT... WHAT?! reveals immediately', (tester) async {
    final s = TestServices(_fifteen);
    await startPrank(tester, s);
    await pumpFor(tester, stageStart(PrankStage.ransom, 15) + const Duration(milliseconds: 500));

    await tester.ensureVisible(find.text('WAIT... WHAT?!'));
    await tester.tap(find.text('WAIT... WHAT?!'));
    await pumpFor(tester, const Duration(milliseconds: 600));
    expect(find.byType(RevealScreen), findsOneWidget);
    await pumpFor(tester, const Duration(seconds: 4));
  });

  testWidgets('triple-tapping the stage title reveals even with the shortcut hidden', (tester) async {
    final s = TestServices(_fifteen.copyWith(showRevealShortcut: false));
    await startPrank(tester, s);
    expect(find.byKey(PrankScreen.revealKey), findsNothing);

    for (var i = 0; i < 3; i++) {
      await tester.tap(find.byKey(PrankScreen.titleKey));
      await tester.pump(const Duration(milliseconds: 50));
    }
    await pumpFor(tester, const Duration(milliseconds: 600));
    expect(find.byType(RevealScreen), findsOneWidget);
    await pumpFor(tester, const Duration(seconds: 4));
  });

  testWidgets('exit asks for confirmation; CONTINUE PRANK resumes', (tester) async {
    final s = TestServices(_fifteen);
    await startPrank(tester, s);
    await pumpFor(tester, const Duration(seconds: 1));

    await tester.tap(find.byKey(PrankScreen.exitKey));
    await pumpFor(tester, const Duration(milliseconds: 300));
    expect(find.byType(ExitConfirmationDialog), findsOneWidget);
    expect(find.text('End the simulation?'), findsOneWidget);

    // The prank is frozen while the dialog is open.
    await pumpFor(tester, const Duration(seconds: 30));
    expect(find.byType(RevealScreen), findsNothing);
    expect(find.textContaining('STAGE 1/6'), findsOneWidget);

    await tester.tap(find.text('CONTINUE PRANK'));
    await pumpFor(tester, const Duration(milliseconds: 300));
    expect(find.byType(ExitConfirmationDialog), findsNothing);

    await pumpFor(tester, stageStart(PrankStage.tracing, 15));
    expect(find.textContaining('STAGE 2/6'), findsOneWidget);

    await tester.tap(find.byKey(PrankScreen.revealKey));
    await pumpFor(tester, const Duration(seconds: 4));
  });

  testWidgets('EXIT SAFELY stops audio, vibration, wakelock and timers', (tester) async {
    final s = TestServices(_fifteen);
    await startPrank(tester, s);
    await pumpFor(tester, stageStart(PrankStage.extracting, 15) + const Duration(milliseconds: 200));
    expect(s.audio.loop, SoundEffect.transfer);
    expect(s.wakelock.enabled, isTrue);

    await tester.tap(find.byKey(PrankScreen.exitKey));
    await pumpFor(tester, const Duration(milliseconds: 300));
    await tester.tap(find.text('EXIT SAFELY'));
    await pumpFor(tester, const Duration(milliseconds: 600));

    expect(find.byType(PrankScreen), findsNothing);
    expect(find.byType(HomeScreen), findsOneWidget);
    expect(s.audio.loop, isNull);
    expect(s.haptics.cancels, greaterThanOrEqualTo(1));
    expect(s.wakelock.enabled, isFalse);

    // Nothing keeps running: no reveal, no new sounds.
    final soundsBefore = s.audio.audible.length;
    await pumpFor(tester, const Duration(seconds: 20));
    expect(find.byType(RevealScreen), findsNothing);
    expect(s.audio.audible.length, soundsBefore);
  });

  testWidgets('without exit confirmation, EXIT leaves immediately', (tester) async {
    final s = TestServices(_fifteen.copyWith(exitConfirmation: false));
    await startPrank(tester, s);

    await tester.tap(find.byKey(PrankScreen.exitKey));
    await pumpFor(tester, const Duration(milliseconds: 600));
    expect(find.byType(ExitConfirmationDialog), findsNothing);
    expect(find.byType(HomeScreen), findsOneWidget);
    expect(find.byType(PrankScreen), findsNothing);
  });

  testWidgets('the system back gesture also offers a safe exit', (tester) async {
    final s = TestServices(_fifteen);
    await startPrank(tester, s);

    // What the Android back button / gesture does.
    final navigator = tester.state<NavigatorState>(find.byType(Navigator));
    await navigator.maybePop();
    await pumpFor(tester, const Duration(milliseconds: 300));
    expect(find.byType(ExitConfirmationDialog), findsOneWidget);

    await tester.tap(find.text('EXIT SAFELY'));
    await pumpFor(tester, const Duration(milliseconds: 600));
    expect(find.byType(HomeScreen), findsOneWidget);
  });

  testWidgets('backgrounding pauses; resuming continues without restarting', (tester) async {
    final s = TestServices(_fifteen);
    await startPrank(tester, s);
    await pumpFor(tester, stageStart(PrankStage.warning, 15) + const Duration(milliseconds: 100));
    expect(find.textContaining('STAGE 3/6'), findsOneWidget);

    await setLifecycle(tester, AppLifecycleState.paused);
    await tester.pump();
    expect(s.audio.loop, isNull);
    expect(s.wakelock.enabled, isFalse);

    await pumpFor(tester, const Duration(minutes: 1));
    expect(find.textContaining('STAGE 3/6'), findsOneWidget, reason: 'time froze');

    await setLifecycle(tester, AppLifecycleState.resumed);
    await tester.pump();
    expect(s.wakelock.enabled, isTrue);
    expect(find.textContaining('STAGE 3/6'), findsOneWidget, reason: 'did not restart');

    final remaining = stageStart(PrankStage.extracting, 15) - stageStart(PrankStage.warning, 15);
    await pumpFor(tester, remaining);
    expect(find.textContaining('STAGE 4/6'), findsOneWidget);

    await tester.tap(find.byKey(PrankScreen.revealKey));
    await pumpFor(tester, const Duration(seconds: 4));
  });

  testWidgets('works end to end with every optional effect disabled', (tester) async {
    final s = TestServices(allEffectsOff);
    await startPrank(tester, s);

    // Typewriter off: the full text is shown at once.
    expect(find.textContaining('ANALYZING TARGET SYSTEM'), findsOneWidget);

    await pumpFor(tester, const Duration(seconds: 16));
    expect(find.byType(RevealScreen), findsOneWidget);
    expect(s.audio.audible, isEmpty);
    expect(s.haptics.pulses, isEmpty);
    await pumpFor(tester, const Duration(seconds: 1));
  });

  testWidgets('PLAY AGAIN starts a fresh run from stage 1', (tester) async {
    final s = TestServices(_fifteen);
    await startPrank(tester, s);
    await pumpFor(tester, stageStart(PrankStage.ransom, 15) + const Duration(seconds: 1));
    await tester.tap(find.byKey(PrankScreen.revealKey));
    await pumpFor(tester, const Duration(milliseconds: 600));

    await tester.ensureVisible(find.byKey(RevealScreen.playAgainKey));
    await tester.tap(find.byKey(RevealScreen.playAgainKey));
    await tester.pump();
    await pumpFor(tester, const Duration(milliseconds: 500));

    expect(find.byType(PrankScreen), findsOneWidget);
    expect(find.textContaining('STAGE 1/6'), findsOneWidget);
    expect(find.byType(RansomScreen), findsNothing);

    await tester.tap(find.byKey(PrankScreen.revealKey));
    await pumpFor(tester, const Duration(seconds: 4));
  });
}
